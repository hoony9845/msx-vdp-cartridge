"""Z80 instruction lengths (for following code forwards)."""

# unprefixed: length of each opcode
_L = [1] * 256
for o in (0x01, 0x11, 0x21, 0x31, 0x22, 0x2A, 0x32, 0x3A, 0xC3, 0xCD,
          0xC2, 0xCA, 0xD2, 0xDA, 0xE2, 0xEA, 0xF2, 0xFA,
          0xC4, 0xCC, 0xD4, 0xDC, 0xE4, 0xEC, 0xF4, 0xFC):
    _L[o] = 3
for o in (0x06, 0x0E, 0x16, 0x1E, 0x26, 0x2E, 0x36, 0x3E, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38,
          0xC6, 0xCE, 0xD6, 0xDE, 0xE6, 0xEE, 0xF6, 0xFE, 0xD3, 0xDB, 0xCB):
    _L[o] = 2


def _ed_len(b):
    if b in (0x43, 0x53, 0x63, 0x73, 0x4B, 0x5B, 0x6B, 0x7B):   # LD (nn),rr / LD rr,(nn)
        return 4
    return 2


def length(m, o):
    """Length of the instruction at m[o] (None past the end)."""
    if o >= len(m):
        return None
    b = m[o]
    if b == 0xED:
        return _ed_len(m[o + 1]) if o + 1 < len(m) else None
    if b in (0xDD, 0xFD):
        if o + 1 >= len(m):
            return None
        c = m[o + 1]
        if c == 0xCB:
            return 4
        if c in (0xDD, 0xFD, 0xED):
            return 1                        # a lone prefix
        if c == 0x36:                       # LD (IX+d),n
            return 4
        if c in (0x21, 0x22, 0x2A):         # LD IX,nn / LD (nn),IX / LD IX,(nn)
            return 4
        n = _L[c]
        # (IX+d) forms take a displacement
        if c in (0x34, 0x35, 0x46, 0x4E, 0x56, 0x5E, 0x66, 0x6E, 0x7E, 0x86, 0x8E, 0x96, 0x9E,
                 0xA6, 0xAE, 0xB6, 0xBE) or 0x70 <= c <= 0x77 and c != 0x76:
            return 3
        if c in (0x26, 0x2E):               # LD IXH/IXL,n
            return 3
        return 1 + n
    return _L[b]


# control flow: unconditional transfers after which the next bytes need not be code
STOP = {0xC3, 0xC9, 0x18, 0xE9}            # JP nn, RET, JR e, JP (HL)
